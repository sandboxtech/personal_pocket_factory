-- 噪声值 → 调色板下标。纯函数、无依赖，能在游戏外单测（见 tests/test_palette.lua）。
--
-- 【这个模块存在的唯一理由是把边界抖开】。
--
-- 最初的写法是直接量化：idx = floor((v + 1) / 2 * n) + 1。
-- 它的问题不在于算错了，而在于它算得【太准】：噪声场是连续的，而这个式子是个阶跃函数，
-- 于是两种砖的分界线恰好落在「噪声值等于某个阈值」的那条等值线上 ——
-- 一条数学意义上完美光滑、视觉上锋利如刀的曲线。整颗星球看起来像一张等高线图，
-- 而不是地形：草地和沙地之间没有任何过渡，一格草紧挨着一格沙。
--
-- 真实地貌（以及原版 Factorio 的地图生成）在两种地块交界处是【互相咬合】的：
-- 靠近边界的地方两种砖犬牙交错地混在一起，越往里越纯。人眼把这种交错读成渐变。
--
-- 做法：量化【之前】给噪声值加一个高频抖动，抖动幅度以「一条色带的宽度」为单位。
-- 于是离边界不到一个抖动幅度的格子会随机落到两边中的一边，边界从一条线变成一条带。
-- 抖动用的是【另一张噪声场】而不是 math.random：
--   · 位置决定结果，和区块生成顺序无关 —— 同一颗种子永远长出同一张图，
--     多人和回滚重放都不会长歪（math.random 的结果取决于它被调用的次序）；
--   · 高频噪声本身有空间连续性，交错的斑点会成簇出现，比纯随机的椒盐噪点自然得多。
local M = {}

-- v      主噪声值，约 [-1,1]，决定这一格【本来】属于哪条色带
-- n      调色板长度
-- jitter 高频噪声值，约 [-1,1]
-- blend  抖动强度，单位是【色带宽度】。0 = 完全不抖（回到锋利的阶跃），
--        1 = 最多可以把一格推到相邻的那条色带里去
function M.index(v, n, jitter, blend)
    if not n or n <= 1 then return 1 end

    -- v 的值域是 [-1,1]（跨度 2），均分成 n 条，所以一条色带在 v 空间里宽 2/n。
    -- 抖动幅度必须换算成这个单位：调色板越长、色带越窄，同样的 blend 才代表同样的
    -- 视觉过渡宽度。写成绝对值的话，19 色的 Nauvis 和 5 色的星球会得到完全不同的效果。
    local band = 2 / n
    local shifted = v + (jitter or 0) * (blend or 0) * band

    local idx = math.floor((shifted + 1) * 0.5 * n) + 1
    -- 夹住：抖动会把边缘格子推出 [-1,1]，而且 v == 1 时式子本身就会算出 n+1。
    if idx < 1 then return 1 end
    if idx > n then return n end
    return idx
end

return M
